#!/usr/bin/env python3
"""Emit a reproducible LVGL 9 PLAIN 4bpp subset, then verify each packed pixel."""
import argparse
import hashlib
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / 'assets/fonts/quota'
FONT = ASSETS / 'NotoSansCJKsc-Regular.otf'


def generate(size=16):
    codepoints = set(range(32, 127))
    for path in (ROOT / 'main').glob('quota_*'):
        if path.suffix in ('.c', '.h'):
            codepoints.update(ord(c) for c in path.read_text(encoding='utf-8') if ord(c) > 127)
    codepoints = sorted(codepoints)
    font = ImageFont.truetype(str(FONT), size)
    bitmap, descriptors = [], ['    {0}']
    for cp in codepoints:
        char = chr(cp)
        left, top, right, bottom = font.getbbox(char, anchor='ls')
        width, height = right - left, bottom - top
        image = Image.new('L', (max(1, width), max(1, height)))
        ImageDraw.Draw(image).text((-left, -top), char, font=font, fill=255, anchor='ls')
        pixels = [round(v * 15 / 255) for v in image.getdata()] if width and height else []
        packed = [(pixels[i] << 4) | (pixels[i + 1] if i + 1 < len(pixels) else 0) for i in range(0, len(pixels), 2)]
        decoded = [n for value in packed for n in (value >> 4, value & 15)][:len(pixels)]
        assert decoded == pixels, f'Packing mismatch U+{cp:04X}'
        descriptors.append(f'    {{.bitmap_index={len(bitmap)}, .adv_w={round(font.getlength(char)*16)}, .box_w={width}, .box_h={height}, .ofs_x={left}, .ofs_y={-bottom}}}')
        bitmap.extend(packed)
    rows = ['    ' + ','.join(f'0x{v:02x}' for v in bitmap[i:i+20]) for i in range(0, len(bitmap), 20)]
    offsets = ','.join(str(cp - codepoints[0]) for cp in codepoints)
    output = '''/* Generated by tools/generate_quota_font.py; Noto Sans CJK SC, SIL OFL 1.1. */
#include "lvgl.h"
static const uint8_t bitmap[] = {
''' + ',\n'.join(rows) + '\n};\nstatic const lv_font_fmt_txt_glyph_dsc_t glyphs[] = {\n' + ',\n'.join(descriptors) + '''
};
static const uint16_t unicode_list[] = {''' + offsets + '''};
static const lv_font_fmt_txt_cmap_t cmaps[] = {{
    .range_start=32, .range_length=''' + str(codepoints[-1] - 31) + ''', .glyph_id_start=1,
    .unicode_list=unicode_list, .glyph_id_ofs_list=NULL,
    .list_length=''' + str(len(codepoints)) + ''', .type=LV_FONT_FMT_TXT_CMAP_SPARSE_TINY
}};
static const lv_font_fmt_txt_dsc_t font_dsc = {
    .glyph_bitmap=bitmap, .glyph_dsc=glyphs, .cmaps=cmaps,
    .kern_dsc=NULL, .kern_scale=0, .cmap_num=1, .bpp=4, .kern_classes=0, .bitmap_format=0
};
const lv_font_t quota_font_SIZE = {
    .get_glyph_dsc=lv_font_get_glyph_dsc_fmt_txt,
    .get_glyph_bitmap=lv_font_get_bitmap_fmt_txt,
    .line_height=LINE_HEIGHT, .base_line=5, .subpx=LV_FONT_SUBPX_NONE,
    .underline_position=-2, .underline_thickness=1, .dsc=&font_dsc
};
''' + ('''const uint32_t quota_font_codepoints[] = {''' + ','.join(str(cp) for cp in codepoints) + '''};
const unsigned quota_font_codepoint_count = sizeof(quota_font_codepoints)/sizeof(quota_font_codepoints[0]);
''' if size == 16 else '')
    output = output.replace('quota_font_SIZE', f'quota_font_{size}').replace('LINE_HEIGHT', str(size + 6))
    inventory = '\n'.join(f'U+{cp:04X} {chr(cp)}' for cp in codepoints) + '\n'
    return output, inventory, len(bitmap)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    outputs = []
    total = 0
    for size in (14, 16):
        source, inventory, byte_count = generate(size)
        outputs.append((f'quota_font_{size}.c', source))
        total += byte_count
        print(f'Quota font {size}px: bitmap={byte_count} bytes')
    outputs.append(('inventory.txt', inventory))
    for name, value in outputs:
        path = ASSETS / name
        if args.check:
            assert path.read_text(encoding='utf-8') == value, f'Regenerate {name}'
        else:
            path.write_text(value, encoding='utf-8', newline='\n')
    print(f'Quota font: PASS; total bitmap={total} bytes; font SHA256={hashlib.sha256(FONT.read_bytes()).hexdigest()}')
